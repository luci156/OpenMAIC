export type SlideDesignSkillId = (typeof SLIDE_DESIGN_SKILLS)[number]['id'];
export type SlideStyle = SlideDesignSkillId | 'consistent-light' | 'ai';

export const DEFAULT_SLIDE_DESIGN_SKILL: SlideDesignSkillId = 'modern-illustration-editorial';

export function getSlideDesignSkill(style?: SlideStyle | null) {
  const id = !style || style === 'consistent-light' ? DEFAULT_SLIDE_DESIGN_SKILL : style;
  if (id === 'ai') return undefined;
  return SLIDE_DESIGN_SKILLS.find((skill) => skill.id === id);
}

export function isSlideDesignSkillId(value: unknown): value is SlideDesignSkillId {
  return typeof value === 'string' && SLIDE_DESIGN_SKILLS.some((skill) => skill.id === value);
}
